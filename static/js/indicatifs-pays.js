function drapeauDepuisIso(iso) {
    if (!iso || iso.length !== 2) return "";
    var base = 0x1F1E6;
    var a = "A".charCodeAt(0);
    return String.fromCodePoint(base + (iso.charCodeAt(0) - a), base + (iso.charCodeAt(1) - a));
}
